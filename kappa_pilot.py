def compute_kappa(data, label=""):
    df = pd.DataFrame(data, columns=["paragraph", "category", "ai_polarity", "theo_polarity"])

    # Cohen's Kappa για πολικότητα
    kappa_pol = cohen_kappa_score(df["ai_polarity"], df["theo_polarity"])

    # Cohen's Kappa για TEC κατηγορία (εδώ πάντα 1.0 γιατί δεν αλλάζει ο θεολόγος)
    kappa_cat = cohen_kappa_score(df["category"], df["category"])

    print(f"\n{'─'*50}")
    print(f"  {label}")
    print(f"{'─'*50}")
    print(f"  Παράγραφοι:          {len(df)}")
    print(f"  Kappa πολικότητας:   {kappa_pol:.4f}")
    print(f"  Kappa κατηγορίας:    {kappa_cat:.4f}")
    print()

    # Ανάλυση ανά κατηγορία
    print("  Συμφωνία ανά TEC κατηγορία:")
    for cat in df["category"].unique():
        sub = df[df["category"] == cat]
        agree = (sub["ai_polarity"] == sub["theo_polarity"]).sum()
        print(f"    {cat:<20} {agree}/{len(sub)} συμφωνούν")

    return kappa_pol


